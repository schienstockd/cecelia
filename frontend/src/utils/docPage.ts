// The building blocks of a generated user-docs page with screenshots (user-docs/using-ai.md,
// user-docs/training.md) and of the README's screenshot block: the page header, the numbered
// Do → You'll see → If it goes wrong steps with their shot, and a composed shot as an <img> (or a
// <picture> when it was captured in the dark scheme too). A page module supplies the words and its
// shot set; the layout lives here once, so the pages read alike and a fix lands on all of them.
// Shots, fixtures and composing: user-docs/shots/README.md.

import { imageFile, shotThemes, type Shot, type ShotSet } from '../../../user-docs/shots/spec.ts'
import { svgEsc as esc } from '../plots/export'

/** One step: Do → You'll see → If it goes wrong, plus Why for what isn't obvious. `shot` = an id of the
 *  page's shot set, shown under the step. */
export interface DocStep {
  title: string
  do: string
  see: string
  ifWrong: string
  why?: string
  optional?: boolean
  shot?: string
  note?: string
}

/** The block under a page's title: who it is for, what they get, what they need, where it ends. */
export interface DocHeader {
  title: string
  tagline: string
  for: string
  get: string
  need: string
  ends: string
}

/** A table cell: no pipes, no line breaks. */
export const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')

/** The page's first line, naming the module that writes it and how to refresh it. */
export const generatedBy = (module: string, test: string): string =>
  `<!-- Generated by frontend/src/utils/${module} — edit there, then \`npx vitest run -u src/utils/${test}\`. -->`

export function docHeader(h: DocHeader): string[] {
  return [
    `# ${h.title}`, '',
    `_${h.tagline}_`, '',
    `- **For:** ${h.for}`,
    `- **You get:** ${h.get}`,
    `- **You need:** ${h.need}`,
    `- **Ends at:** ${h.ends}`,
    '',
  ]
}

export interface ImageOpts {
  /** Path prefix of the composed images, as the page links them ('images/' from a user-docs page). */
  base: string
  /** Throw when the shot is not composed, instead of printing a placeholder line. */
  strict?: boolean
}

/** A composed shot at the width it was composed for (`user-docs/images/images.json`, written by
 *  scripts/docshots/compose.mjs). Captured in both schemes, it is a <picture> GitHub shows in the
 *  reader's. Not composed yet: a visible placeholder line, or an error when `strict`. */
export function docImage(set: ShotSet, x: Shot, alt: string, widths: Record<string, number>, o: ImageOpts): string {
  const themes = shotThemes(set, x)
  const w = widths[imageFile(x, themes[0]).replace(/\.(png|jpg)$/, '')]
  if (!w) {
    if (o.strict) throw new Error(`shot ${x.id} is not composed (pixi run doc-images)`)
    return `_Screenshot \`${x.id}\` not composed yet (pixi run doc-shots, then doc-images)._`
  }
  const img = `<img src="${o.base}${imageFile(x, themes[0])}" width="${w}" alt="${esc(alt)}">`
  const dark = themes.includes('dark') && themes[0] !== 'dark' ? `${o.base}${imageFile(x, 'dark')}` : null
  return dark ? `<picture><source media="(prefers-color-scheme: dark)" srcset="${dark}">${img}</picture>` : img
}

/** The shot of `set` called `id`; throws on an id the set does not have. */
export function shotOf(set: ShotSet, id: string): Shot {
  const x = set.shots.find(s => s.id === id)
  if (!x) throw new Error(`shot set ${set.id} has no shot ${id}`)
  return x
}

/** Numbered steps, each with its shot, starting at `from`. */
export function docSteps(steps: DocStep[], set: ShotSet, widths: Record<string, number>, from = 1): string[] {
  return steps.flatMap((s, i) => [
    `### ${from + i}. ${s.title}${s.optional ? ' (optional)' : ''}`,
    '',
    `**Do:** ${s.do}`,
    '',
    `**You’ll see:** ${s.see}`,
    '',
    ...(s.why ? [`**Why:** ${s.why}`, ''] : []),
    `**If it goes wrong:** ${s.ifWrong}`,
    '',
    ...(s.shot ? [docImage(set, shotOf(set, s.shot), s.title, widths, { base: 'images/' }), ''] : []),
    ...(s.note ? ['> [!NOTE]', `> ${s.note}`, ''] : []),
  ])
}

/** Every shot a page shows, from its steps and any figure it places itself — for the test that a page
 *  shows exactly its set's shots. */
export const stepShots = (steps: DocStep[]): string[] => steps.flatMap(s => (s.shot ? [s.shot] : []))
