// The screenshots at the top of the repository's README.md: the block between its `docshots` markers,
// generated from the `readme` shot set (user-docs/shots/readme.ts) so every caption's sample and numbers
// are the fixture's measured facts (user-docs/images/facts.json), never typed. The first shot is the
// large one; the rest sit side by side under "What it looks like". A screenshot captured in both
// schemes is a <picture> GitHub shows in the reader's; a picture of the image has one file.
// `utils/readmeShots.test.ts` fails when the README's block is stale.

import { README_SHOTS } from '../../../user-docs/shots/readme.ts'
import { fillFacts, imageFile, shotThemes, type Shot } from '../../../user-docs/shots/spec.ts'

export const README_START = '<!-- docshots:start'
export const README_END = '<!-- docshots:end -->'

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

/** A shot's caption with the fixture's facts filled in; throws on a fact the fixture did not measure. */
function caption(x: Shot, facts: Record<string, number | string>): string {
  const c = fillFacts(x.caption ?? '', facts)
  if (c.missing.length) throw new Error(`readme shot ${x.id}: no measured ${c.missing.join(', ')} (pixi run doc-fixture, doc-shots, doc-images)`)
  return c.text
}

function image(x: Shot, widths: Record<string, number>, alt: string): string {
  const themes = shotThemes(README_SHOTS, x)
  const file = (t: (typeof themes)[number]) => `user-docs/images/${imageFile(x, t)}`
  const w = widths[imageFile(x, themes[0]).replace(/\.(png|jpg)$/, '')]
  if (!w) throw new Error(`readme shot ${x.id} is not composed (pixi run doc-images)`)
  const img = `<img src="${file(themes[0])}" width="${w}" alt="${esc(alt)}">`
  const dark = themes.includes('dark') && themes[0] !== 'dark' ? file('dark') : null
  return dark ? `<picture><source media="(prefers-color-scheme: dark)" srcset="${dark}">${img}</picture>` : img
}

export function renderReadmeShots(facts: Record<string, number | string>, widths: Record<string, number>): string {
  const [hero, ...rest] = README_SHOTS.shots
  const cell = (x: Shot) => {
    const c = caption(x, facts)
    return `<td valign="top">${image(x, widths, c)}<br><sub>${esc(c)}</sub></td>`
  }
  const heroCaption = caption(hero, facts)
  return [
    `${README_START} — generated by frontend/src/utils/readmeShots.ts from user-docs/shots/readme.ts: edit there, then \`npx vitest run src/utils/readmeShots.test.ts -u\` -->`,
    `<p align="center">${image(hero, widths, heroCaption)}<br><sub>${esc(heroCaption)}</sub></p>`,
    '',
    '## What it looks like',
    '',
    `<table><tr>${rest.map(cell).join('')}</tr></table>`,
    README_END,
  ].join('\n')
}

/** `readme` with its docshots block replaced by `block`; throws when the markers are missing. */
export function spliceReadme(readme: string, block: string): string {
  const a = readme.indexOf(README_START), b = readme.indexOf(README_END)
  if (a < 0 || b < a) throw new Error('README.md has no docshots block (its start and end markers)')
  return readme.slice(0, a) + block + readme.slice(b + README_END.length)
}
