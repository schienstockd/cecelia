// The screenshots at the top of the repository's README.md: the block between its `docshots` markers,
// generated from the `readme` shot set (user-docs/shots/readme.ts) so every caption's sample and numbers
// are the fixture's measured facts (user-docs/images/facts.json), never typed. The first shot is the large
// figure (with any shot `beside` it drawn into the same image by compose.mjs); a `heroRow` shot sits in the
// same top row with its own caption (one sample per figure, each caption naming its own); the rest, if any,
// sit side by side under "What it looks like". A screenshot captured in both
// schemes is a <picture> in the reader's OS scheme (the README set itself is light only: GitHub's theme
// is not what <picture> follows); a picture of the image has one file.
// `utils/readmeShots.test.ts` fails when the README's block is stale.

import { README_SHOTS } from '../../../user-docs/shots/readme.ts'
import { fillFacts, type Shot } from '../../../user-docs/shots/spec.ts'
import { docImage } from './docPage'
import { svgEsc as esc } from '../plots/export'

export const README_START = '<!-- docshots:start'
export const README_END = '<!-- docshots:end -->'


/** A shot's caption with the fixture's facts filled in; throws on a fact the fixture did not measure. */
function caption(x: Shot, facts: Record<string, number | string>): string {
  const c = fillFacts(x.caption ?? '', facts)
  if (c.missing.length) throw new Error(`readme shot ${x.id}: no measured ${c.missing.join(', ')} (pixi run doc-fixture, doc-shots, doc-images)`)
  return c.text
}

const image = (x: Shot, widths: Record<string, number>, alt: string): string =>
  docImage(README_SHOTS, x, alt, widths, { base: 'user-docs/images/', strict: true })

export function renderReadmeShots(facts: Record<string, number | string>, widths: Record<string, number>): string {
  const [first, ...others] = README_SHOTS.shots
  // one beside another is drawn into that one's image (compose.mjs)
  const top = [first, ...others.filter(x => x.heroRow && !x.beside)]
  const rest = others.filter(x => !x.beside && !x.heroRow)
  // equal columns: GitHub sizes an auto table by its text, so a longer caption took the wider column
  const cell = (x: Shot, n: number) => {
    const c = caption(x, facts)
    return `<td valign="top" width="${Math.floor(100 / n)}%">${image(x, widths, c)}<br><sub>${esc(c)}</sub></td>`
  }
  const lone = (x: Shot) => { const c = caption(x, facts); return `<p align="center">${image(x, widths, c)}<br><sub>${esc(c)}</sub></p>` }
  return [
    `${README_START} — generated by frontend/src/utils/readmeShots.ts from user-docs/shots/readme.ts: edit there, then \`npx vitest run src/utils/readmeShots.test.ts -u\` -->`,
    top.length === 1 ? lone(first) : `<table align="center"><tr>${top.map(x => cell(x, top.length)).join('')}</tr></table>`,
    ...(rest.length ? ['', '## What it looks like', '', `<table><tr>${rest.map(x => cell(x, rest.length)).join('')}</tr></table>`] : []),
    README_END,
  ].join('\n')
}

/** `readme` with its docshots block replaced by `block`; throws when the markers are missing. */
export function spliceReadme(readme: string, block: string): string {
  const a = readme.indexOf(README_START), b = readme.indexOf(README_END)
  if (a < 0 || b < a) throw new Error('README.md has no docshots block (its start and end markers)')
  return readme.slice(0, a) + block + readme.slice(b + README_END.length)
}
