# One section pinning the bioformats2raw --series N output-subdir resolver used by the
# import task to decide which subdir ccid.json's filepath["default"] should point at:
# single-series bf2raw default (0/), --series 3 output (only 3/), multi-series with
# preference, flat-store layout (multiscales AT the root, returns ""), and nothing exists
# → nothing. Extracted from suite.jl to keep it small enough to merge without EOF
# conflicts on every append. The extracted file loads inside this file's aggregating
# testset scope, so any helpers defined earlier in suite.jl are still in scope (lexical
